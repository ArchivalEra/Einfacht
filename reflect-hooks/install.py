#!/usr/bin/env python3
"""Wire Einfacht's gates into your repo -- **without taking hook seats**.

`git config core.hooksPath` is git's **global override switch**: once it is
set, git **stops looking at** `.git/hooks/` entirely, so husky / lefthook /
pre-commit (Python) / handwritten hooks are all **silently disabled** (the
"deployed does not mean running" state this repo exists to eliminate).

So this repo only **exposes one entry** (`reflect-hooks/hook.py`); hook
placement stays yours.

## Three ways in, all reversible

    (no args) [target repo]  print the wiring instructions, **writes no file**
    --chain                  install **chained** wrappers into `.git/hooks/`
                             (an existing same-name hook => run it first,
                             then Einfacht)
    --uninstall              undo (restores original hooks and unsets legacy hooksPath)

Python keeps the entry inside `check_i18n`'s AST-scanned surface (it only
reads `.py`) and avoids depending on `sh` on Windows.

**The generated hook wrappers are still shell** -- git invokes them, so they
must be minimal executables; but they are generated by this script, with
fixed content and **no user-visible Chinese at all** (one exec line and one
fixed comment).
"""
from __future__ import annotations

import os
import stat
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL_REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(TOOL_REPO, "zreflect"))

from gate import activate_or_fatal, meta  # noqa: E402
from i18n import M  # noqa: E402

GATE = os.path.join(HERE, "hook.py")
PHASE_OF = {"pre-commit": "commit", "pre-push": "push"}


def _git(repo, *args):
    try:
        p = subprocess.run(["git", "-C", repo, *args],
                           capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
    except (OSError, subprocess.SubprocessError):
        return None, ""
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def _chmod_x(path):
    mode = os.stat(path).st_mode
    os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _hooks_dir(repo):
    """Resolve the git hooks directory (supports normal repos, worktrees, and submodules)."""
    rc, out = _git(repo, "rev-parse", "--git-path", "hooks")
    if rc == 0 and out.strip():
        p = out.strip()
        return p if os.path.isabs(p) else os.path.join(repo, p)
    return os.path.join(repo, ".git", "hooks")


def _wrapper_body(name, phase):
    """Content of the chained wrapper. **Fixed**, preserves stdin across `$PREV`, no Chinese."""
    py = sys.executable or "python3"
    return (
        "#!/bin/sh\n"
        "# Einfacht chain wrapper (generated by reflect-hooks/install.py --chain)\n"
        'HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\n'
        'PREV="$HERE/%s.einfacht-prev"\n'
        'if [ -x "$PREV" ]; then\n'
        "  STDIN=$(cat)\n"
        '  { [ -n "$STDIN" ] && printf \'%%s\\n\' "$STDIN"; } | "$PREV" "$@" || exit $?\n'
        '  { [ -n "$STDIN" ] && printf \'%%s\\n\' "$STDIN"; } | "%s" "%s" %s "$(git rev-parse --show-toplevel)"\n'
        "  exit $?\n"
        "fi\n"
        'exec "%s" "%s" %s "$(git rev-parse --show-toplevel)"\n'
        % (name, py, GATE, phase, py, GATE, phase)
    )


def install_chain(repo):
    """Install the chained wrappers. Returns (rc, lines).

    Warning: **check `core.hooksPath` first**: once git has it set, it
    **ignores `.git/hooks` entirely**. Writing wrappers there is then
    **writing files that will never execute** -- after installing, `git
    commit` looks perfectly fine and `installed chain` gets printed, yet the
    hooks never ran once.

    This is the "deployed does not mean running" family this repo exists to
    eliminate -- so **refuse on the spot; install nothing**.
    """
    hooks = _hooks_dir(repo)
    if not os.path.isdir(hooks):
        return 2, [str(M("install.no_hooks_dir", path=hooks))]
    rc, current = _git(repo, "config", "core.hooksPath")
    if rc == 0 and (current or "").strip():
        # A core.hooksPath already exists => git ignores `.git/hooks`.
        # Installing a chain there is a no-op.
        return 2, [str(M("install.chain_blocked_by_hookspath",
                         value=current.strip())),
                   str(M("install.chain_blocked_fix"))]
    lines = []
    for name, phase in PHASE_OF.items():
        target = os.path.join(hooks, name)
        prev = target + ".einfacht-prev"
        if os.path.isfile(target):
            try:
                body = open(target, encoding="utf-8", errors="replace").read()
            except OSError:
                body = ""
            if ("hook.py" not in body and "gate.py" not in body
                    and "einfacht-gate.sh" not in body):
                os.replace(target, prev)
                lines.append(str(M("install.kept_existing", name=name)))
        with open(target, "w", encoding="utf-8") as fh:
            fh.write(_wrapper_body(name, phase))
        _chmod_x(target)
        lines.append(str(M("install.installed_chain", name=name)))
    lines.append(str(M("install.chain_done")))
    return 0, lines


def uninstall(repo):
    """Undo install styles. Returns (rc, lines)."""
    lines = []
    rc, _o = _git(repo, "config", "--unset", "core.hooksPath")
    lines.append(str(M("install.legacy_removed")) if rc == 0
                 else str(M("install.legacy_was_not_set")))
    hooks = _hooks_dir(repo)
    for name in PHASE_OF:
        target = os.path.join(hooks, name)
        prev = target + ".einfacht-prev"
        if os.path.isfile(target):
            try:
                body = open(target, encoding="utf-8", errors="replace").read()
            except OSError:
                body = ""
            if ("hook.py" in body or "gate.py" in body
                    or "einfacht-gate.sh" in body):
                os.unlink(target)
                lines.append(str(M("install.chain_removed", name=name)))
        if os.path.isfile(prev):
            os.replace(prev, target)
            lines.append(str(M("install.restored_original", name=name)))
    return 0, lines


def usage_lines():
    return [str(M("install.usage")),
            str(M("install.usage_no_target")),
            str(M("install.usage_chain")),
            str(M("install.usage_uninstall"))]


def instructions():
    """No args: the wiring instructions (**writes no file**)."""
    return [str(M("install.intro")),
            str(M("install.example_commit", gate=GATE)),
            str(M("install.example_push", gate=GATE)),
            str(M("install.chain_hint")),
            str(M("install.uninstall_hint")),
            str(M("install.why_not_hookspath"))]


def main(argv):
    mode = argv[0] if argv else ""
    target = argv[1] if len(argv) > 1 else ""
    repo = os.path.abspath(target) if target else TOOL_REPO
    if target and not os.path.exists(os.path.join(repo, ".git")):
        print(str(M("install.not_a_repo", path=repo)), file=sys.stderr)
        return 2
    if mode in ("--help", "-h"):
        print("\n".join(usage_lines()))
        return 0
    if mode == "":
        print("\n".join(instructions()))
        return 0
    if mode == "--chain":
        rc, lines = install_chain(repo)
    elif mode == "--uninstall":
        rc, lines = uninstall(repo)
    else:
        print("\n".join(usage_lines()), file=sys.stderr)
        return 2
    for ln in lines:
        print(ln, file=(sys.stderr if rc else sys.stdout))
    return rc


# -- Self-verification -------------------------------------------------------

def _cases():
    import shutil
    import tempfile  # noqa: PLC0415

    def mk():
        d = tempfile.mkdtemp()
        _git(d, "init", "-q")
        return d

    return [
        ("install.no_args_prints_only", lambda: _no_args_case(mk, shutil)),
        ("★ install.unknown_mode_is_2",
         lambda: _run_cli(["--bogus"], quiet=True) == 2),
        ("★ install.not_a_repo_is_2",
         lambda: _run_cli(["--chain", "/nonexistent-xyz"], quiet=True) == 2),
        ("★ install.chain_keeps_existing", lambda: _chain_case(mk, shutil)),
        ("★ install.uninstall_restores", lambda: _uninstall_case(mk, shutil)),
        ("★ install.chain_refused_when_hookspath_set",
         lambda: _chain_blocked_case(mk, shutil)),
        ("★ install.missing_hooks_dir_is_2",
         lambda: _missing_hooks_case(mk, shutil)),
    ]


def _run_cli(argv, quiet=False):
    """Walk the CLI dispatch once, return rc.

    `quiet=True` (**selftest only**): print nothing -- selftest output is the
    interface a human checks.
    """
    if quiet:
        import contextlib  # noqa: PLC0415
        import io  # noqa: PLC0415
        with contextlib.redirect_stdout(io.StringIO()), \
                contextlib.redirect_stderr(io.StringIO()):
            return main(argv)
    return main(argv)


def _no_args_case(mk, shutil):
    d = mk()
    try:
        before = set(os.listdir(_hooks_dir(d)))
        rc = _run_cli([], quiet=True)
        after = set(os.listdir(_hooks_dir(d)))
        return rc == 0 and before == after
    finally:
        shutil.rmtree(d, True)


def _chain_case(mk, shutil):
    d = mk()
    try:
        hooks = _hooks_dir(d)
        pre = os.path.join(hooks, "pre-commit")
        open(pre, "w", encoding="utf-8").write("#!/bin/sh\necho mine\n")
        _chmod_x(pre)
        rc, _lines = install_chain(d)
        prev = pre + ".einfacht-prev"
        body = open(pre, encoding="utf-8").read()
        return rc == 0 and os.path.isfile(prev) and "hook.py" in body
    finally:
        shutil.rmtree(d, True)


def _chain_blocked_case(mk, shutil):
    """With a `core.hooksPath` already set, `--chain` must return rc=2 **and
    write no wrapper**."""
    d = mk()
    try:
        _git(d, "config", "core.hooksPath", "reflect-hooks")
        rc, _lines = install_chain(d)
        wrapper = os.path.join(_hooks_dir(d), "pre-commit")
        wrote = os.path.isfile(wrapper) and "hook.py" in (
            open(wrapper, encoding="utf-8").read() if os.path.isfile(wrapper)
            else "")
        return rc == 2 and not wrote
    finally:
        shutil.rmtree(d, True)


def _uninstall_case(mk, shutil):
    d = mk()
    try:
        hooks = _hooks_dir(d)
        pre = os.path.join(hooks, "pre-commit")
        open(pre, "w", encoding="utf-8").write("#!/bin/sh\necho mine\n")
        _chmod_x(pre)
        install_chain(d)
        uninstall(d)
        body = open(pre, encoding="utf-8").read()
        return "hook.py" not in body and "echo mine" in body
    finally:
        shutil.rmtree(d, True)


def _missing_hooks_case(mk, shutil):
    d = mk()
    try:
        import shutil as _sh  # noqa: PLC0415
        _sh.rmtree(_hooks_dir(d), True)
        rc, _lines = install_chain(d)
        return rc == 2
    finally:
        shutil.rmtree(d, True)


def _selftest_entry():
    rc = activate_or_fatal()
    if rc:
        return rc
    from gate import selftest  # noqa: PLC0415
    return selftest(M("gate.title.install"), _cases())


if __name__ == "__main__":
    if "--selftest" in sys.argv[1:]:
        sys.exit(_selftest_entry())
    rc = activate_or_fatal()
    sys.exit(rc or main(sys.argv[1:]))


